"""D3/D4: preview a full diagnosis chain and attribution on archived analysis.

Not the D6 report generator. It demonstrates that a real analysis payload
produces an honest diagnosis (or no diagnosis) and a verified source level.
"""

import argparse
import json

from rdebug.diagnostics.diagnosis_engine import build_diagnoses
from rdebug.diagnostics.finding_builder import build_findings
from rdebug.diagnostics.mapping_resolver import attach_to_report, resolve_attribution
from rdebug.diagnostics.report_model import (
    empty_report,
    set_section,
    validate_report,
)


def preview(analysis, metadata=None, capture=None):
    findings = build_findings(analysis)
    diagnoses = build_diagnoses(findings)
    mappings = [resolve_attribution(analysis, metadata)]
    report = empty_report(capture=capture)
    set_section(report, "findings", "present", None, findings)
    attach_to_report(report, diagnoses["diagnoses"], mappings)
    set_section(report, "executive_summary", "present", None, {
        "findingCount": findings["findingCount"],
        "anomalyCount": findings["anomalyCount"],
        "diagnosisCount": diagnoses["diagnosisCount"],
        "highestSourceLevel": mappings[0]["highestVerifiedLevel"],
    })
    set_section(report, "workload_overview", "present", None,
                {"resource": analysis.get("resource"), "summary": analysis.get("summary")})
    set_section(report, "evidence_coverage", "present", None, {
        "analysisStatus": analysis.get("analysisStatus"),
        "unresolved": analysis.get("causal", {}).get("unresolved", []),
        "limitations": findings["limitations"],
    })
    set_section(report, "impact_analysis", "insufficient_evidence",
                "no impact assessment rule is defined for an observation-only finding", {})
    for name in ("recommendations", "change_proposals", "verification_plan"):
        set_section(report, name, "insufficient_evidence",
                    "generated by D5/D6, not by this preview", {})
    validate_report(report)
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(prog="diagnostic-preview")
    ap.add_argument("analysis_json")
    ap.add_argument("--json", dest="json_path")
    args = ap.parse_args(argv)
    with open(args.analysis_json, encoding="utf-8") as fh:
        analysis = json.load(fh)
    text = json.dumps(preview(analysis), indent=2, ensure_ascii=False)
    if args.json_path:
        with open(args.json_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text + "\n")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
